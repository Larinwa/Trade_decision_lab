"""Exports the existing engine's CSV evidence into workbook and readable PDF."""
from pathlib import Path
import pandas as pd
from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill, Alignment
from openpyxl.utils import get_column_letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, PageBreak
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.units import inch
from xml.sax.saxutils import escape

REPORT_FILES = ['model_a_findings.csv','model_a_year_coverage.csv','model_a_world_reconciliation.csv',
                'model_b_analysis_periods.csv','model_b_partner_rankings.csv','model_b_sensitivity_comparison.csv',
                'model_c_decision_assessment.csv','model_a_source_row_traceability.csv']

def _tables(output_dir):
    out = Path(output_dir)
    for flow in ('import','export','total_trade_import','total_trade_export'):
        for name in REPORT_FILES:
            path = out / flow / name
            if path.exists():
                yield flow, name, pd.read_csv(path, low_memory=False, dtype={"commodity_code": str, "cmdCode": str})

def _scalar(v):
    if pd.isna(v): return None
    if isinstance(v, (bool,int,float,str)): return v
    if hasattr(v, 'item'):
        try: return _scalar(v.item())
        except Exception: pass
    return str(v)

def generate_reports(output_dir, llm_brief=None):
    out=Path(output_dir); out.mkdir(parents=True, exist_ok=True)
    book=Workbook(); book.remove(book.active); sheets=[]
    for flow,name,frame in _tables(out):
        # Excel has a hard limit of 1,048,576 rows; detailed CSVs remain the complete source.
        if len(frame)>1048575: continue
        sheet_name=(flow[:3]+'_'+name.replace('model_','').replace('.csv',''))[:31]
        if sheet_name in sheets: sheet_name=(sheet_name[:27]+str(len(sheets)))[:31]
        sheets.append(sheet_name)
        sh=book.create_sheet(sheet_name)
        columns=[str(x) for x in frame.columns]
        if not columns: continue
        sh.append(columns)
        for cell in sh[1]:
            cell.fill=PatternFill('solid', fgColor='17324D')
            cell.font=Font(bold=True,color='FFFFFF')
            cell.alignment=Alignment(wrap_text=True)
        sh.freeze_panes='A2'
        for row in frame.itertuples(index=False,name=None):
            sh.append([_scalar(v) for v in row])
        for index,col in enumerate(columns,1):
            sh.column_dimensions[get_column_letter(index)].width=min(40,max(14,len(col)+2))
        sh.auto_filter.ref=sh.dimensions
    if not sheets: book.create_sheet('No_data')
    xlsx=out/'Trade_Decision_Lab_Results.xlsx'
    book.save(xlsx)
    styles=getSampleStyleSheet(); story=[Paragraph('Trade Decision Lab | Research results',styles['Title']),Spacer(1,12),Paragraph('Evidence generated by the original UN Comtrade analytical engine. Screening flags are not confirmed errors. Decision implications are potential, not observed changes in behaviour.',styles['BodyText']),Spacer(1,12)]
    for flow,name,frame in _tables(out):
        if name=='model_a_source_row_traceability.csv':
            story.append(Paragraph(f'{escape(flow)}: full row traceability supplied in the Excel workbook and CSV.',styles['BodyText'])); continue
        story.append(Paragraph(escape(flow.replace('_',' ').title()+' | '+name.replace('.csv','').replace('_',' ').title()),styles['Heading2']))
        story.append(Paragraph(f'{len(frame):,} records. Full detailed output is in the accompanying Excel workbook and CSV.',styles['BodyText']))
        if name == 'model_c_decision_assessment.csv' and not frame.empty:
            for _, record in frame.iterrows():
                hs = str(record.get('commodity_code', '')).zfill(4)
                title = f"{record.get('flow', flow)} | {hs} | {record.get('scenario', '')} | {record.get('classification', '')}"
                story.append(Paragraph(escape(title), styles['Heading3']))
                story.append(Paragraph(f"Records: {record.get('records', 0)}; country partners: {record.get('country_partners', 0)}", styles['BodyText']))
                for prefix, label in [('partner_prioritisation', 'Partner prioritisation'), ('concentration', 'Concentration analysis'), ('unit_value', 'Unit-value comparison')]:
                    verdict = record.get(prefix + '_fitness', 'Not assessed')
                    reason = record.get(prefix + '_reason', '')
                    action = record.get(prefix + '_action', '')
                    story.append(Paragraph(f"<b>{escape(label)} fitness: {escape(str(verdict))}</b>", styles['BodyText']))
                    story.append(Paragraph('Reason: ' + escape(str(reason)), styles['BodyText']))
                    story.append(Paragraph('Recommended action: ' + escape(str(action)), styles['BodyText']))
                story.append(Spacer(1, 9))
            continue
        if not frame.empty:
            # Keep PDF readable; full data remain in workbook and CSV.
            cols=list(frame.columns[:5]); view=frame[cols].head(12).fillna('')
            rows=[[Paragraph(escape(str(x)[:28]),styles['BodyText']) for x in cols]]
            for record in view.itertuples(index=False,name=None):
                rows.append([Paragraph(escape(str(v)[:70]),styles['BodyText']) for v in record])
            table=Table(rows,repeatRows=1,colWidths=[(7.1*inch)/len(cols)]*len(cols),hAlign='LEFT')
            table.setStyle(TableStyle([('BACKGROUND',(0,0),(-1,0),colors.HexColor('#E4EEF6')),('VALIGN',(0,0),(-1,-1),'TOP'),('BOTTOMPADDING',(0,0),(-1,-1),7),('LINEBELOW',(0,0),(-1,0),.4,colors.grey)]))
            story.append(table)
        story.append(Spacer(1,14))
    story.append(Paragraph('Methodological limitations',styles['Heading2']))
    story.append(Paragraph('Interpretation is limited to the supplied trade records, chosen commodity codes, configured periods, rules and sensitivity treatments. World aggregates must not be summed with country partners. See the preserved methodology and limitations documents.',styles['BodyText']))
    if llm_brief:
        story.append(Paragraph('LLM interpretation (not an independent calculation)',styles['Heading2']))
        for paragraph in str(llm_brief).split('\n'):
            if paragraph.strip(): story.append(Paragraph(escape(paragraph),styles['BodyText']))
    pdf=out/'Trade_Decision_Lab_Report.pdf'
    SimpleDocTemplate(str(pdf),pagesize=(595,842),leftMargin=38,rightMargin=38,topMargin=40,bottomMargin=40).build(story)
    return {'xlsx':xlsx,'pdf':pdf}
